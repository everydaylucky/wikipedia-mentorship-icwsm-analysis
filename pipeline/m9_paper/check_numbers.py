"""
check_numbers.py: check the numbers in the paper one by one

Module: M9 (PLAN.md M9; CODE_PLAN.md section 5, M9)

1. What it does
    Reads pipeline/m9_paper/paper_numbers.yaml (generated by tools/build_paper_numbers.py).
    For each entry: open the result file, use the query to pick exactly one row, take the value in the
    "column" column, multiply it by scale, and compare it with the value in the paper.
    Writes results/paper_check.md and results/paper_check.csv.

2. Why it is designed this way
    Every number in the paper must be traceable to one cell in one result file.
    After changing the data, turning on a fix, or editing the paper, rerun this script and you see right away
    which numbers changed.

    Decision rules:
        kind = "value": |result x scale - paper value| <= tol, where tol is half of the precision shown in the paper;
        kind = "lt" (the paper says "<.001"): result x scale < paper value.

3. Inputs
    paper_numbers.yaml; the result files under results/.

4. Outputs
    results/paper_check.md: counts of matches and mismatches per table, plus details of every mismatch;
    results/paper_check.csv: the check result for every entry.

6. Possible errors and how they are handled
    The result file does not exist: recorded as no_result (that part has not been reproduced yet).
    The query does not return exactly one row: recorded as lookup_error, with the row count. This means the entry was registered wrongly.

7. How to run
    python -m pipeline.m9_paper.check_numbers
    python run_all.py --legacy            # stage A: checks run automatically after the reproduction
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

import config
from pipeline.common.io import write_table
from pipeline.common.runlog import base_parser, setup_logging

YAML = config.ROOT / "pipeline" / "m9_paper" / "paper_numbers.yaml"


def check_one(e: dict, cache: dict[str, pd.DataFrame]) -> dict:
    """Check one entry. Returns a dict with status and result."""
    path = config.RESULTS / e["source"]
    out = {**e, "result": None, "diff": None}
    if not path.exists():
        return {**out, "status": "no_result"}
    if str(path) not in cache:
        cache[str(path)] = pd.read_csv(path)
    df = cache[str(path)]
    try:
        sub = df.query(e["query"]) if e.get("query") else df
    except Exception as ex:                              # the registered query is wrong
        return {**out, "status": "lookup_error", "detail": str(ex)}
    if len(sub) != 1 or e["column"] not in sub.columns:
        return {**out, "status": "lookup_error", "detail": f"{len(sub)} rows"}
    val = sub[e["column"]].iloc[0]
    if pd.isna(val):
        return {**out, "status": "mismatch", "result": None}
    val = float(val) * float(e.get("scale", 1))
    if e.get("kind") == "lt":
        ok = val < e["value"]
        return {**out, "result": val, "status": "match" if ok else "mismatch"}
    diff = val - e["value"]
    return {**out, "result": val, "diff": diff, "status": "match" if abs(diff) <= e["tol"] else "mismatch"}


def table_of(id_: str) -> str:
    """The table an entry belongs to (the first part of its id)."""
    return id_.split(".")[0]


def main(argv: list[str] | None = None) -> None:
    ap = base_parser("Check every number in the paper against the result files.")
    ap.parse_args(argv)
    log = setup_logging("m9")
    doc = yaml.safe_load(YAML.read_text())
    cache: dict[str, pd.DataFrame] = {}
    rows = [check_one(e, cache) for e in doc["numbers"]]
    df = pd.DataFrame(rows)
    df["table"] = df["id"].map(table_of)
    write_table(config.RESULTS / "paper_check.csv", df)

    summ = df.groupby("table")["status"].value_counts().unstack(fill_value=0)
    lines = ["# Paper number check", "", f"- Registered numbers: {len(df)} (`{YAML.relative_to(config.ROOT)}`)",
             f"- Match {int((df.status == 'match').sum())}, mismatch {int((df.status == 'mismatch').sum())}, "
             f"no result yet {int((df.status == 'no_result').sum())}, registration error {int((df.status == 'lookup_error').sum())}",
             "", "## Summary by table", "", "```", summ.to_string(), "```", "",
             "## Tables not yet covered (reproduced by later modules)", ""]
    lines += [f"- `{k}`: {v}" for k, v in doc.get("pending_tables", {}).items()]
    bad = df[df.status.isin(["mismatch", "lookup_error"])]
    lines += ["", f"## Mismatches and registration errors ({len(bad)})", "",
              "| id | Location | Paper | Result | Diff | Notes |", "|---|---|---|---|---|---|"]
    for r in bad.itertuples():
        res = "" if r.result is None or pd.isna(r.result) else f"{r.result:.4f}"
        dif = "" if r.diff is None or pd.isna(r.diff) else f"{r.diff:+.4f}"
        note = getattr(r, "note", "") if isinstance(getattr(r, "note", ""), str) else ""
        lines.append(f"| {r.id} | {r.where} | {r.paper} | {res} | {dif} | {note} {getattr(r, 'detail', '') or ''} |")
    out = config.RESULTS / "paper_check.md"
    out.write_text("\n".join(lines) + "\n")
    log.info("checked %d numbers: %s", len(df), df.status.value_counts().to_dict())
    log.info("report: %s", out)


if __name__ == "__main__":
    main(sys.argv[1:])
